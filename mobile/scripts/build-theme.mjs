// Generates src/theme/tokens.ts from docs/design/tokens.json, the snapshot of the Buraco
// design system (https://claude.ai/artifact/BmhzdPTKPP13K83By3DMLy). Never edit
// tokens.ts by hand: update the snapshot and run `npm run theme`.
// A test fails when tokens.ts is out of date with the snapshot.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(here, '../../docs/design/tokens.json');
const TARGET = join(here, '../src/theme/tokens.ts');

// Bundled font files (expo-font) per family and weight. React Native picks a weight by
// font file, not by fontWeight, once a custom font is used.
const FONT_FILES = {
  sans: { 400: 'AtkinsonHyperlegibleNext_400Regular', 600: 'AtkinsonHyperlegibleNext_600SemiBold',
          700: 'AtkinsonHyperlegibleNext_700Bold' },
  display: { 600: 'Fraunces_600SemiBold' },
};

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (v) => (typeof v === 'number' ? v : Number(String(v).replace('px', '')));

export function build(tokens) {
  const themes = tokens.color.themes.map((t) => t.id);
  const colors = Object.fromEntries(themes.map((id) => [id, {}]));
  for (const t of tokens.color.tokens) {
    for (const id of themes) {
      const value = typeof t.value === 'string' ? t.value : t.value[id] ?? t.value[themes[0]];
      colors[id][camel(t.name)] = value;
    }
  }

  const list = (family, map) => Object.fromEntries(tokens[family].tokens.map((t) => [camel(t.name), map(t.value)]));
  const space = list('spacing', px);
  const radius = list('radius', px);
  const size = list('size', px);
  const opacity = list('opacity', Number);
  const shadow = Object.fromEntries(themes.map((id) => [id, Object.fromEntries(tokens.shadow.tokens.map((t) =>
    [camel(t.name), typeof t.value === 'string' ? t.value : t.value[id] ?? t.value[themes[0]]]))]));

  const type = {};
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const family = s.family ?? group.family;
      const fontFamily = FONT_FILES[family]?.[s.fontWeight];
      if (!fontFamily) throw new Error(`no bundled font for ${family} ${s.fontWeight} (style ${s.name})`);
      type[camel(s.name)] = {
        fontFamily,
        fontSize: px(s.fontSize),
        lineHeight: px(s.lineHeight),
        ...(s.letterSpacing ? { letterSpacing: px(s.letterSpacing) } : {}),
      };
    }
  }

  const json = (v) => JSON.stringify(v, null, 2);
  return `// GENERATED by scripts/build-theme.mjs from docs/design/tokens.json. Do not edit.
// Design system: https://claude.ai/artifact/BmhzdPTKPP13K83By3DMLy

export const colors = ${json(colors)} as const;

export type ThemeName = keyof typeof colors;
export type ColorName = keyof (typeof colors)['light'];

export const space = ${json(space)} as const;

export const radius = ${json(radius)} as const;

export const size = ${json(size)} as const;

export const opacity = ${json(opacity)} as const;

/** CSS box-shadow strings (React Native supports \`boxShadow\` on both platforms). */
export const shadow = ${json(shadow)} as const;

export const type = ${json(type)} as const;

export type TextStyleName = keyof typeof type;

/** Every font file the theme uses, for expo-font. */
export const fontFiles = ${json([...new Set(Object.values(type).map((t) => t.fontFamily))].sort())} as const;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = build(JSON.parse(readFileSync(SOURCE, 'utf8')));
  if (process.argv.includes('--check')) {
    // CI / tests: fail when someone edited tokens.ts by hand or forgot to regenerate.
    if (readFileSync(TARGET, 'utf8') !== output) {
      console.error('src/theme/tokens.ts is out of date: run `npm run theme`.');
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, output);
    console.log(`wrote ${TARGET}`);
  }
}
